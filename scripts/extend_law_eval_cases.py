def main() -> None:
    cases = [json.loads(line) for line in DATASET.read_text(encoding="utf-8").splitlines() if line.strip()]
    if len(cases) == 200 and all(case.get("variant_of") for case in cases[100:]):
        print(f"Already contains {len(cases)} cases: {DATASET}")
        return
    if len(cases) != 100 or len(NO_TITLE_QUESTIONS) != 40 or len(TITLE_QUESTIONS) != 60:
        raise ValueError("Expected 100 original cases, 40 no-title and 60 titled variants")
    additions = []
    for case, question in zip(cases[30:70], NO_TITLE_QUESTIONS, strict=True):
        additions.append({**case, "id": f"{case['id']}-without-title", "title_keywords": [], "case_facts": question, "variant_of": case["id"]})
    for case, question in zip(cases[:60], TITLE_QUESTIONS, strict=True):
        additions.append({**case, "id": f"{case['id']}-paraphrase", "case_facts": question, "variant_of": case["id"]})
    all_cases = cases + additions
    ids = [case["id"] for case in all_cases]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate case ID")
    DATASET.write_text("\n".join(json.dumps(case, ensure_ascii=False, separators=(",", ":")) for case in all_cases) + "\n", encoding="utf-8")
    print(f"Wrote {len(all_cases)} cases to {DATASET}")


if __name__ == "__main__":
    main()
